"""Extract Apache OpenOffice's native shape data into a classic JS data file.
No C++ is executed; the numeric expression parser accepts constant integer arithmetic only.
Run with python3 -I tools/legacy/geometry-data.py. Source pin recorded in provenance.
"""
import ast
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
REF = ROOT / 'refs/openoffice/main'

def comments(s):
    return re.sub(r'/\*.*?\*/|//[^\n]*', '', s, flags=re.S)

source = comments((REF / 'svx/source/customshapes/EnhancedCustomShapeGeometry.cxx').read_text(encoding='latin1'))
header = comments((REF / 'svx/inc/svx/msdffdef.hxx').read_text(encoding='latin1'))
structs = comments((REF / 'svx/inc/svx/EnhancedCustomShapeGeometry.hxx').read_text(encoding='latin1'))
constants = {'NULL': 0, 'Mx80000000': 0x80000000}
for name, number in re.findall(r'#define\s+(\w+)\s+(-?(?:0[xX][a-fA-F0-9]+|\d+))\b', header + structs):
    constants[name] = int(number, 0)
for name, number in re.findall(r'(mso_spt\w+)\s*=\s*(\d+)\b', header):
    constants[name] = int(number)
constants['mso_sptNotPrimitive'] = 0

def number(s):
    s = s.strip().replace('MSO_I', '| Mx80000000')
    s = re.sub(r'\b(0[xX][0-9a-fA-F]+|\d+)[uUlL]+\b', r'\1', s)
    tree = ast.parse(s, mode='eval').body
    def read(n):
        if isinstance(n, ast.Constant) and isinstance(n.value, int): return n.value
        if isinstance(n, ast.Name): return constants[n.id]
        if isinstance(n, ast.UnaryOp) and isinstance(n.op, (ast.USub, ast.UAdd)):
            v = read(n.operand); return -v if isinstance(n.op, ast.USub) else v
        if isinstance(n, ast.BinOp) and isinstance(n.op, ast.BitOr): return read(n.left) | read(n.right)
        if isinstance(n, ast.BinOp) and isinstance(n.op, ast.Add): return read(n.left) + read(n.right)
        if isinstance(n, ast.BinOp) and isinstance(n.op, ast.Sub): return read(n.left) - read(n.right)
        if isinstance(n, ast.BinOp) and isinstance(n.op, ast.Mult): return read(n.left) * read(n.right)
        if isinstance(n, ast.BinOp) and isinstance(n.op, ast.Div): return int(read(n.left) / read(n.right))
        if isinstance(n, ast.BinOp) and isinstance(n.op, ast.LShift): return read(n.left) << read(n.right)
        raise ValueError('Unexpected data expression: ' + s)
    return read(tree)

def array(s):
    tokens = re.findall(r'[{},]|[^{},]+', s)
    pos = 0
    def group():
        nonlocal pos
        assert tokens[pos] == '{'; pos += 1; out = []
        while tokens[pos] != '}':
            tok = tokens[pos]
            if tok == '{': out.append(group())
            elif tok == ',' or not tok.strip(): pos += 1
            else: out.append(number(tok)); pos += 1
        pos += 1
        return out
    return group()

arrays = {}
for kind, name, data in re.findall(r'static const (\w+)\s+(\w+)\[\]\s*=\s*(\{.*?\})\s*;', source, re.S):
    if kind in ('SvxMSDffVertPair', 'SvxMSDffCalculationData', 'SvxMSDffTextRectangles', 'SvxMSDffHandle', 'sal_Int32', 'sal_uInt16'):
        arrays[name] = array(data)
shapes = {}
for name, data in re.findall(r'static const mso_CustomShape\s+(\w+)\s*=\s*\{(.*?)\}\s*;', source, re.S):
    fields = [f.strip() for f in data.split(',')]
    if len(fields) != 17: raise ValueError((name, len(fields)))
    def ref(index):
        key = re.sub(r'^\([^)]*\)', '', fields[index]).strip()
        return [] if key == 'NULL' else arrays[key]
    guides = ref(4)
    guides = [[g[0], *(g[1] if isinstance(g[1], list) else g[1:]) ] for g in guides]
    defaults = ref(6)
    shapes[name] = dict(v=ref(0), s=ref(2), g=guides, a=defaults[1:] if defaults else [],
                        t=ref(7), w=number(fields[9]), h=number(fields[10]),
                        stretch=[number(fields[11]),number(fields[12])], c=ref(13), handles=ref(15))
result = {}
body = source[source.index('const mso_CustomShape* GetCustomShapeContent'):]
for cases, name in re.findall(r'((?:case\s+mso_spt\w+\s*:\s*)+)pCustomShape\s*=\s*&([\w]+);\s*break;', body):
    for case in re.findall(r'case\s+(mso_spt\w+)', cases):
        result[constants[case]] = shapes[name]
output = ROOT / 'public/common/legacy/native-geometry.js'
notice = '''/* Derived from Apache OpenOffice main/svx/source/customshapes/EnhancedCustomShapeGeometry.cxx
 * (Apache-2.0), Copyright The Apache Software Foundation. Native OfficeArt shape definitions.
 * Generated by tools/legacy/geometry-data.py; source pin be094486. */
(function(root){'use strict';root.L.legacy.nativeGeometry='''
output.write_text(notice + json.dumps(result, separators=(',', ':')) + ";})(typeof window!=='undefined'?window:globalThis);\n")
print(f'{len(result)} native shape definitions, {output.stat().st_size} bytes')
