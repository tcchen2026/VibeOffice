"""Generate missing Office single-byte decoders from Unicode's mapping data.

Run with python3 -I tools/legacy/codepages.py. Downloads are cached on the host
mount, with URLs and SHA-256 hashes recorded beside them. No runtime fetches.
"""
import hashlib
import json
from pathlib import Path
import re
import time
import urllib.request

ROOT = Path(__file__).resolve().parents[2]
CACHE = ROOT / 'tmp/legacy/artifacts/codepages'
CACHE.mkdir(parents=True, exist_ok=True)
BASE = 'https://www.unicode.org/Public/MAPPINGS/VENDORS/MICSFT/'
ICU = 'https://raw.githubusercontent.com/unicode-org/icu/release-77-1/icu4c/source/data/mappings/'
sources = {cp: BASE + f'PC/CP{cp}.TXT' for cp in
           [437, 737, 775, 850, 852, 855, 857, 860, 861, 862, 863, 864, 865, 866, 869, 874]}
sources.update({10006: BASE + 'MAC/GREEK.TXT', 10029: BASE + 'MAC/LATIN2.TXT',
                10079: BASE + 'MAC/ICELAND.TXT', 10081: BASE + 'MAC/TURKISH.TXT',
                720: ICU + 'ibm-720_P100-1997.ucm', 858: ICU + 'ibm-858_P100-1997.ucm'})
manifest = []


def fetch(url):
    path = CACHE / url.rsplit('/', 1)[1]
    if not path.exists():
        for attempt in range(3):
            try:
                with urllib.request.urlopen(url, timeout=30) as response:
                    data = response.read()
                path.write_bytes(data)
                break
            except OSError:
                if attempt == 2:
                    raise
                time.sleep(1)
    data = path.read_bytes()
    manifest.append({'url': url, 'sha256': hashlib.sha256(data).hexdigest(), 'bytes': len(data)})
    return data.decode('utf-8-sig')


tables = {}
for cp, url in sorted(sources.items()):
    data = fetch(url)
    table = ['\ufffd'] * 256
    if url.endswith('.ucm'):
        # Only round-trip and to-Unicode mappings; never use encoder fallbacks.
        rows = [(int(byte, 16), int(code, 16)) for code, byte, precision in
                re.findall(r'^<U([0-9A-Fa-f]+)>\s+\\x([0-9A-Fa-f]{2})\s+\|([03])', data, re.M)]
    else:
        rows = [(int(byte, 16), int(code, 16)) for byte, code in
                re.findall(r'^0x([0-9A-Fa-f]{2})\s+0x([0-9A-Fa-f]+)', data, re.M)]
    for byte, code in rows:
        if code > 0xffff:
            raise ValueError('Single-code-unit table required')
        table[byte] = chr(code)
    if len(rows) < 200:
        raise ValueError(f'Incomplete mapping {cp}: {len(rows)} entries')
    tables[cp] = ''.join(table)

license_text = fetch('https://www.unicode.org/license.txt')
(ROOT / 'public/common/legacy/UNICODE-LICENSE.txt').write_text(license_text, encoding='utf-8')
header = '''/* Derived from Unicode Microsoft codepage mappings and ICU 77.1 mapping data (Unicode-3.0).
 * Copyright 1991-2026 Unicode, Inc. See UNICODE-LICENSE.txt.
 * ICU data also Copyright (C) 1995-2007 International Business Machines Corporation and others.
 * Generated by tools/legacy/codepages.py; source URLs and hashes in tmp/legacy/artifacts/codepages/sources.json.
 * Full 256-byte tables include non-ASCII-compatible pages such as CP864. */
(function (root) {
  'use strict';
  root.L.legacy.codepages = Object.freeze({
'''
body = ''.join(f'    {cp}: {json.dumps(table, ensure_ascii=True)},\n' for cp, table in sorted(tables.items()))
(ROOT / 'public/common/legacy/codepages.js').write_text(header + body +
    "  });\n})(typeof window !== 'undefined' ? window : globalThis);\n", encoding='utf-8')
(CACHE / 'sources.json').write_text(json.dumps(manifest, indent=2) + '\n')
print(f'Generated {len(tables)} codepages; source hashes in {CACHE / "sources.json"}')
