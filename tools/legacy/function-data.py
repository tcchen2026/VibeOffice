#!/usr/bin/env python3
"""Extract constant BIFF function metadata from the pinned Apache POI resource."""
import hashlib
import json
import pathlib
import re
import subprocess

commit = 'ae62bb5116b9aee19ebd5834e3a82066132c9f7f'
source = 'poi/src/main/resources/org/apache/poi/ss/formula/function/functionMetadata.txt'
repo = pathlib.Path('refs/poi').resolve()
data = subprocess.check_output(['git', '-c', 'safe.directory=' + str(repo), '-C', str(repo), 'show', commit + ':' + source])
functions = {}
for line in data.decode().splitlines():
    if not line or line.startswith('#'):
        continue
    fields = line.split('\t')
    index, name, minimum, maximum = fields[:4]
    functions[int(index)] = [name, int(minimum), int(maximum)]
atp_source = 'poi/src/main/java/org/apache/poi/ss/formula/atp/AnalysisToolPak.java'
atp = subprocess.check_output(['git', '-c', 'safe.directory=' + str(repo), '-C', str(repo), 'show', commit + ':' + atp_source])
addin_names = sorted(set(re.findall(r'\br\(m,\s*"([A-Z][A-Z0-9_.]+)"', atp.decode())))
header = '/* Derived from Apache POI ' + source + ' (Apache-2.0).\n * Pin ' + commit + '; source SHA256 ' + hashlib.sha256(data).hexdigest() + '.\n * Generated by tools/legacy/function-data.py; constant names/arities only. */\n'
header += '/* Analysis ToolPak names derived from Apache POI ' + atp_source + ' (Apache-2.0); SHA256 ' + hashlib.sha256(atp).hexdigest() + '. */\n'
body = '(function(root){\n  \'use strict\';\n  root.L.legacy.xls.functions=Object.freeze(' + json.dumps(functions, separators=(',', ':')) + ');\n  root.L.legacy.xls.addinFunctions=new Set(' + json.dumps(addin_names, separators=(',', ':')) + ');\n})(typeof window!==\'undefined\'?window:globalThis);\n'
pathlib.Path('public/common/legacy/xls-functions.js').write_text(header + body)
print(json.dumps({'functions': len(functions), 'source': source, 'commit': commit, 'sha256': hashlib.sha256(data).hexdigest(), 'addinFunctions': len(addin_names), 'addinSource': atp_source, 'addinHash': hashlib.sha256(atp).hexdigest()}))
